"""Part 2, tier 2b test: does the LLM label event-to-market relations correctly, and do the bounds hold?
(docs/event_pipeline/probabilities.md step 3; DECISIONS #228.)

  python scripts/part2_relations.py            # dry run: calls and cost
  python scripts/part2_relations.py --confirm  # one classify call per event (capped, cached) -> results/part2_relations.md

Pairs: docs/pmrm/part2_pairs.json (12 events x 2-3 live Kalshi markets, every relation type; labelled by the build assistant,
for the trainer to review). Scored: agreement with the gold label(s); and for events that ARE a listed market ("same"), whether
the bounds from the OTHER markets' relations contain that market's own price (a bound that excludes it is an error).
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from dotenv import load_dotenv  # noqa: E402

load_dotenv(ROOT / ".env")

from worsey import config  # noqa: E402
from worsey.planb import probability as PR  # noqa: E402
from worsey.pmrm.ic import budget as ICB  # noqa: E402


class CappedLLM:
    """Routes PR.classify's call through the per-run caps and the permanent label cache (SPEC 6.1)."""
    def __init__(self, run, tag):
        self.run, self.tag = run, tag

    def create(self, **kw):
        kw.pop("_source", None)
        k = ICB.key("part2_relations", {"event": self.tag}, kw["messages"][0]["content"], kw["model"])
        return self.run.call(k, **kw)


def main(confirm: bool):
    import argparse as ap

    from worsey.cli import _data
    pairs = json.loads((ROOT / "docs/pmrm/part2_pairs.json").read_text(encoding="utf-8"))["events"]
    data = _data(ap.Namespace(synthetic=False, quote_tag=None))
    uni = {m["id"]: m for m in data.event_markets()}
    missing = [i for e in pairs for i, _ in e["pairs"] if i not in uni]
    from worsey.agent.llm import AnthropicLLM
    run = ICB.Run("part2_relations", config.EXPERT_MODEL, AnthropicLLM() if confirm else None, confirmed=confirm)
    run.plan(len(pairs), in_tok=2500, out_tok=600)
    print(f"{len(pairs)} events, {sum(len(e['pairs']) for e in pairs)} pairs; missing from today's universe: {missing}")
    if not confirm:
        return
    rows, checks = [], []
    for e in pairs:
        cands = [uni[i] for i, _ in e["pairs"] if i in uni]
        rel = {r["id"]: r for r in PR.classify(CappedLLM(run, e["event"]), e["event"], cands)}
        for i, gold in e["pairs"]:
            got = rel.get(i, {}).get("relation")
            rows.append({"event": e["event"], "market": i, "title": uni.get(i, {}).get("title"), "gold": gold, "got": got,
                         "ok": got in gold, "threshold": rel.get(i, {}).get("threshold"), "deadline": rel.get(i, {}).get("deadline"),
                         "why": rel.get(i, {}).get("why")})
        same = [i for i, g in e["pairs"] if g == ["same"] and i in uni]
        for s in same:          # bounds from the other markets must contain the listed market's own price
            truth = PR._p(uni[s])
            others = [r for i, r in rel.items() if i != s]
            b = PR.bounds(others, {i: PR._p(uni[i]) for i in rel if i != s and i in uni})
            checks.append({"event": e["event"], "market": s, "price": truth, "lo": b["lo"], "hi": b["hi"],
                           "holds": truth is None or b["lo"] - 1e-9 <= truth <= b["hi"] + 1e-9, "from": b["markets"]})
        # tier 2a on the strike/deadline pairs: the derived probability, for the record
        for r in rows[-len(e["pairs"]):]:
            m = uni.get(r["market"])
            if r["got"] == "other_strike" and r["threshold"] is not None and m:
                r["derived"] = PR.derive_strike(m, list(uni.values()), float(r["threshold"]), rel[r["market"]].get("above") is not False)
            elif r["got"] == "other_deadline" and r["deadline"] and m:
                r["derived"] = PR.derive_deadline(m, list(uni.values()), r["deadline"])
    acc = sum(r["ok"] for r in rows) / len(rows)
    out = {"pairs": len(rows), "agreement": acc, "bounds_checks": checks, "bounds_hold": all(c["holds"] for c in checks),
           "rows": rows, "llm": run.summary()}
    (ROOT / "docs/pmrm/results/part2_relations.json").write_text(json.dumps(out, indent=1, default=str), encoding="utf-8")
    L = ["# Part 2, tier 2b: relation labels and bounds", "",
         "Generated by `scripts/part2_relations.py`. Pairs in `docs/pmrm/part2_pairs.json` (labelled by the build assistant; **for the trainer to review**).", "",
         f"- **Agreement with the gold labels: {sum(r['ok'] for r in rows)} of {len(rows)} ({acc:.0%})**",
         f"- **Bounds checks** (events that are themselves listed: do the other markets' bounds contain its price?): "
         f"{sum(c['holds'] for c in checks)} of {len(checks)} hold", f"- Cost: ${run.summary().get('est_usd', 0):.2f}", "",
         "| event | market | gold | model | derived (tier 2a) | why |", "|---|---|---|---|---|---|"]
    for r in rows:
        d = r.get("derived") or {}
        dv = f"{d['p']:.3f}" if d.get("p") is not None else (d.get("reason", "")[:40] if d else "")
        L.append(f"| {r['event'][:55]} | {r['market']} | {'/'.join(r['gold'])} | {r['got']}{'' if r['ok'] else ' ✗'} | {dv} | {(r['why'] or '')[:60]} |")
    L += ["", "| listed event | its price | bounds from the others | holds |", "|---|---|---|---|"]
    for c in checks:
        L.append(f"| {c['event'][:60]} | {c['price']} | [{c['lo']:.2f}, {c['hi']:.2f}] from {', '.join(c['from']) or 'none'} | {'yes' if c['holds'] else 'NO'} |")
    (ROOT / "docs/pmrm/results/part2_relations.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in out.items() if k not in ("rows",)}, indent=1, default=str))
    for r in rows:
        if not r["ok"]:
            print("MISS", r["event"][:50], r["market"], r["gold"], "->", r["got"], "|", r["why"])


if __name__ == "__main__":
    a = argparse.ArgumentParser()
    a.add_argument("--confirm", action="store_true")
    main(a.parse_args().confirm)
