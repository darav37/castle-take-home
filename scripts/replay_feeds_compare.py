"""Before/after test for the past-event replay feeding the proposal call (the design brief).

  python scripts/replay_feeds_compare.py --tag before            # DRY RUN: books, calls and cost; nothing is called
  python scripts/replay_feeds_compare.py --tag before --confirm  # one capped proposal call per book
  python scripts/replay_feeds_compare.py --tag after --confirm   # same, after the change
  python scripts/replay_feeds_compare.py --report                # write docs/pmrm/results/replay_feeds_proposals.md

Per book: the replay's top 3 one-off categories (live.scan, code), the watchlist with live proposals (discovery.watchlist,
capped through pmrm.ic.budget and cached by prompt), how many proposals are a top-3 category, headline and tail risks.
"""

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from dotenv import load_dotenv  # noqa: E402

load_dotenv(ROOT / ".env")

from worsey import config  # noqa: E402
from worsey.pmrm.ic import budget as ICB  # noqa: E402

OUT = ROOT / "docs/pmrm/results"
RAW = OUT / "replay_feeds_proposals.json"
OPT = lambda t, kind, k, n: {"ticker": t, "option": {"kind": kind, "strike": k, "expiry": "2027-01-15", "contracts": n}}  # noqa: E731
BOOKS = {
    "the trainer's example book": [{"ticker": "PFE", "value_usd": 20000}, {"ticker": "WDC", "value_usd": 15000}, {"ticker": "TSLA", "value_usd": 20000},
                             {"ticker": "URA", "value_usd": 15000}, {"ticker": "GLD", "value_usd": 20000}, OPT("USO", "put", 157, 2)],
    "Normal book": [{"ticker": "SPY", "value_usd": 40000}, {"ticker": "QQQ", "value_usd": 15000}, {"ticker": "BND", "value_usd": 20000},
                    {"ticker": "IWM", "value_usd": 5000}, {"ticker": "AAPL", "value_usd": 10000}, {"ticker": "MSFT", "value_usd": 10000}],
    "Weird book": [{"ticker": "GDX", "value_usd": 15000}, {"ticker": "URA", "value_usd": 10000}, {"ticker": "DBA", "value_usd": 10000},
                   {"ticker": "EWZ", "value_usd": 10000}, {"ticker": "KRE", "value_usd": 10000}, {"ticker": "MRNA", "value_usd": 10000},
                   {"ticker": "UNG", "value_usd": 10000}, {"ticker": "SLV", "value_usd": 5000}, OPT("USO", "put", 157, 2), OPT("TLT", "call", 90, 5)],
}


class CappedLLM:
    """discovery.propose's llm, routed through the PMRM per-run caps and the permanent prompt-keyed cache (SPEC §6.1)."""

    def __init__(self, run: ICB.Run, book: str):
        self.run, self.book = run, book

    def create(self, **kw):
        kw.pop("_source", None)
        pr = kw["messages"][0]["content"]
        return self.run.call(ICB.key("replay_feeds_compare", {"book": self.book}, pr, kw["model"]), **kw)


def one_book(name: str, holdings: list, run: ICB.Run) -> dict:
    import argparse as ap
    from worsey import discovery as D
    from worsey.agent import tools
    from worsey.agent.session import Session
    from worsey.cli import _data
    from worsey.planb import live
    s = Session(_data(ap.Namespace(synthetic=False, quote_tag=None)))
    tools.load_portfolio(s, holdings=holdings)
    scan = live.scan(s, 91, n=len(live.CATEGORIES) + 5)
    ev = sorted([r for r in scan["risks"] if r["kind"] == "one-off event"], key=lambda r: r["bad_case_1_in_10_usd"])
    top3 = [r["risk_id"].split(":", 1)[1] for r in ev[:3]]
    w = D.watchlist(s, CappedLLM(run, name), horizon_days=91)
    props = [r for r in w["headline"] + w["tail_risks"] + w["noise_for_you"] if r.get("source") == "proposal"]
    keep = ("title", "category", "from_history", "from_history_bad_case_usd", "linked_to", "full_impact_usd", "odds", "odds_source", "why_this_book")
    pr = [{k: r.get(k) for k in keep} for r in props]
    return {"book": name, "as_of": w["as_of"], "top3": top3,
            "top3_bad_case_usd": {r["risk_id"].split(":", 1)[1]: r["bad_case_1_in_10_usd"] for r in ev[:3]},
            "proposals_shown": pr, "proposals_total": w["counts"]["proposals"], "proposals_error": w.get("proposals_error"),
            "category_in_top3": sum(p["category"] in top3 for p in pr),
            "from_history_in_top3": sum((p.get("from_history") or "") in top3 for p in pr),
            "headline": [(r["title"], r["source"], r.get("full_impact_usd", r.get("swing_usd"))) for r in w["headline"]],
            "tail_risks": [(r["title"], r.get("category"), r.get("full_impact_usd")) for r in w["tail_risks"]],
            "threshold_usd": w["impact_threshold_usd"]}


def report():
    from worsey.planb import live
    R = json.loads(RAW.read_text(encoding="utf-8"))
    cw = lambda c: live.CATEGORY_WORDS.get(c, c or "—")  # noqa: E731
    money = lambda x: "—" if x is None else f"{x / 1000:+.1f}k"  # noqa: E731
    L = ["# The past-event replay feeds the proposal call: before and after", "",
         "Task: the design brief. Generated by `scripts/replay_feeds_compare.py`. "
         "Each run is one live proposal call per book (stream B), capped and cached per SPEC §6.1. "
         "\"Shown\" proposals are the ones the watchlist keeps (headline, tail risks, noise); a proposal folded or deduplicated "
         "away is counted in the total but not listed.", ""]
    for book in BOOKS:
        b, a = R.get("before", {}).get(book), R.get("after", {}).get(book)
        if not (b and a):
            continue
        L += [f"## {book}", "",
              f"Replay's top 3 one-off categories (bad case 1 in 10): " + "; ".join(f"{cw(c)} {money(a['top3_bad_case_usd'][c])}" for c in a["top3"]), ""]
        for tag, r in (("Before", b), ("After", a)):
            if r.get("proposals_error"):
                L += [f"**{tag}:** not run, the proposal call was refused ({r['proposals_error']}). Rerun: "
                      f"`python scripts/replay_feeds_compare.py --tag {tag.lower()} --confirm` (redoes only the failed books).", ""]
                continue
            L += [f"**{tag}** ({r['as_of']}; {r['proposals_total']} proposals, {len(r['proposals_shown'])} shown; "
                  f"category in the top 3: **{r['category_in_top3']}**" + (f"; from_history in the top 3: **{r['from_history_in_top3']}**" if tag == "After" else "") + ")", "",
                  "| proposal | category | from history | linked to | book move |", "|---|---|---|---|---|"]
            for p in r["proposals_shown"]:
                fh = f"{cw(p['from_history'])} ({money(p.get('from_history_bad_case_usd'))})" if p.get("from_history") else ""
                L.append(f"| {p['title']} | {cw(p['category'])} | {fh} | {(p.get('linked_to') or 'tail risk')[:60]} | {money(p['full_impact_usd'])} |")
            L += ["", "Headline: " + "; ".join(f"{t} ({money(x)})" for t, _, x in r["headline"]),
                  "", "Tail risks: " + ("; ".join(f"{t} ({money(x)})" for t, _, x in r["tail_risks"]) or "none"), ""]
    L += ["## Cost", "", "; ".join(f"{t}: {R[t]['_llm']['calls']} calls, ${R[t]['_llm']['est_usd']}" for t in ("before", "after") if t in R), ""]
    (OUT / "replay_feeds_proposals.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote", OUT / "replay_feeds_proposals.md")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", choices=["before", "after"])
    ap.add_argument("--confirm", action="store_true")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    if a.report:
        return report()
    from worsey.agent.llm import AnthropicLLM
    run = ICB.Run("replay_feeds_compare", config.EXPERT_MODEL, AnthropicLLM() if a.confirm else None, confirmed=a.confirm)
    run.plan(len(BOOKS), in_tok=9000, out_tok=2500)
    if not a.confirm:
        return
    R = json.loads(RAW.read_text(encoding="utf-8")) if RAW.exists() else {}
    prev = R.get(a.tag, {})
    done = {n: r for n, r in prev.items() if not n.startswith("_") and not r.get("proposals_error") and r.get("proposals_total")}
    R[a.tag] = {name: done.get(name) or one_book(name, h, run) for name, h in BOOKS.items()}   # redo only failed books
    old = prev.get("_llm") or {}
    R[a.tag]["_llm"] = {**run.summary(), "calls": run.calls + old.get("calls", 0), "est_usd": round(run.usd + old.get("est_usd", 0.0), 3),
                        "ran_at": datetime.now().isoformat(timespec="minutes")}
    RAW.write_text(json.dumps(R, indent=1, default=str), encoding="utf-8")
    for name, r in R[a.tag].items():
        if not name.startswith("_"):
            print(name, "| top3:", r["top3"], "| in top3:", r["category_in_top3"], "/", len(r["proposals_shown"]), "| err:", r["proposals_error"])
    print(run.summary())


if __name__ == "__main__":
    main()
