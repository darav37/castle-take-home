"""Before/after for #235: an option's underlier moves exactly like the stock (legs + shared own noise). Code only, $0.

  python scripts/option_underlier_legs.py   -> docs/pmrm/results/option_underlier_legs.md

Book: the trainer's example book plus WDC calls (WDC is held, and the AI-bubble event carries a semis-down leg).
  watchlist path   discovery.impact on the committed "AI bubble burst in 2026?" label: the WDC calls' underlier move
                   and P&L before (factors only) and after (factors + the same legs as the stock)
  one-event path   live.price with the analyst's semis-down sector leg: before = factors only for the option and
                   independent noise; after = the same legs and the stock's own noise draw
"""

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from dotenv import load_dotenv  # noqa: E402

load_dotenv(ROOT / ".env")

OUT = ROOT / "docs/pmrm/results/option_underlier_legs.md"


def main():
    import argparse as ap

    from worsey import discovery as D
    from worsey.agent import tools
    from worsey.agent.session import Session
    from worsey.cli import _data
    from worsey.planb import live
    s = Session(_data(ap.Namespace(synthetic=False, quote_tag=None)))
    S = s.data.prices(["WDC"])["WDC"]
    book = [{"ticker": "PFE", "value_usd": 20000}, {"ticker": "WDC", "value_usd": 15000}, {"ticker": "TSLA", "value_usd": 20000},
            {"ticker": "URA", "value_usd": 15000}, {"ticker": "GLD", "value_usd": 20000},
            {"ticker": "USO", "option": {"kind": "put", "strike": 157, "expiry": "2027-01-15", "contracts": 2}},
            {"ticker": "WDC", "option": {"kind": "call", "strike": round(S * 1.05), "expiry": "2027-01-15", "contracts": 3}}]
    tools.load_portfolio(s, holdings=book)
    ctx = D.context(s)
    lab = next(v for v in D.labels().values() if v["title"].startswith("AI bubble burst"))
    after = D.impact(ctx, lab)
    # before: the same event with the option's underlier on factors only (what discovery.impact did up to #234)
    spec = {"severity": lab.get("severity", "moderate"), "factor_signs": {k: (1 if d == "+" else -1) for k, d in lab["factor_signs"].items()},
            "factor_sizes": lab.get("factor_sizes") or {}}
    d = live.real_event_draws(spec, ctx["db"], ctx["cov"]["daily_noise_usd"], ctx["fd"])
    rows = []
    for o in ctx["opts"]:
        u = o["pos"].underlying
        f_only = float(o["beta"] @ d["f"])
        sl = ctx["SL"].get(u, {})
        sec = sum(sl.get("loading", 0) * ctx["SP"].get(sc, {}).get("two_day_move_median", 0.0) * np.sqrt(2) * (1 if dr == "+" else -1)
                  for sc, dr in lab.get("sectors") or [] if sl.get("sector") == sc)
        stock_mv = float(ctx["Bh"].loc[u].to_numpy() @ d["f"]) + sec if u in ctx["Bh"].index else None
        rows.append({"option": o["pos"].label, "underlier_sector": sl.get("sector"), "stock_move": stock_mv,
                     "before_move": f_only, "before_pnl": float(live.option_pnl(o, [f_only])[0]),
                     "after_move": f_only + sec, "after_pnl": float(live.option_pnl(o, [f_only + sec])[0])})
    after_opt = {p["ticker"]: p["full_impact_usd"] for p in after["by_position"]}

    # the one-event path: a semis-down sector leg written by the analyst
    sec = next((r["underlier_sector"] for r in rows if r["option"].startswith("WDC")), None) or "semis"
    s.__dict__["planb_spec"] = {"severity": "major", "category": "regulatory_court", "factor_signs": spec["factor_signs"],
                                "factor_sizes": spec["factor_sizes"], "market_moving": True}
    s.__dict__["planb_evidence"] = s.__dict__.get("planb_evidence") or {}
    pr = live.price(s, sector_news=[{"sector": sec, "direction": "negative"}])
    one = next(o for o in pr["options"] if o["position"].startswith("WDC"))
    stock = next(p for p in pr["by_position"] if p["ticker"] == "WDC")
    res = {"watchlist": rows, "watchlist_book_after": after["full_impact_usd"], "one_event": {"stock_move": stock["move_if_it_happens"],
           "option_underlier_move": one["underlying_move_middle"], "option_pnl_middle": one["pnl_middle_usd"],
           "legs": one.get("underlier_legs"), "book_range": pr.get("range_9_in_10_usd") or pr.get("end_of_day", {}).get("range_9_in_10_usd")}}
    L = ["# An option's underlier moves exactly like the stock (DECISIONS #235)", "",
         "Generated by `scripts/option_underlier_legs.py` (code only). Book: the trainer's example book plus 3 WDC calls "
         f"(strike {round(S * 1.05)}, Jan 15 2027); WDC is held, so its calls should move with it.", "",
         "## Watchlist path: \"AI bubble burst in 2026?\" (label: semis down, software down)", "",
         "| option | underlier's sector | stock's move | option's underlier move before | after | option P&L before | after |",
         "|---|---|---|---|---|---|---|"]
    for r in rows:
        sm = "–" if r["stock_move"] is None else f"{r['stock_move']:+.2%}"
        L.append(f"| {r['option']} | {r['underlier_sector'] or 'none'} | {sm} | {r['before_move']:+.2%} | {r['after_move']:+.2%} | "
                 f"${r['before_pnl']:+,.0f} | ${r['after_pnl']:+,.0f} |")
    L += ["", "The USO puts are unchanged (USO has no sector leg and isn't held directly).", "",
          f"## One-event path: the same event priced with a {sec}-down sector leg", "",
          f"- WDC stock's move: {res['one_event']['stock_move']:+.2%}",
          f"- the WDC calls' underlier move: {res['one_event']['option_underlier_move']:+.2%} (now the same as the stock's)",
          f"- the calls' P&L in the middle case: ${res['one_event']['option_pnl_middle']:+,.0f}",
          f"- legs applied to the underlier: {res['one_event']['legs']}", "",
          "**Shared own noise:** within each of the 10,000 draws, WDC stock and the WDC calls now use the same own-noise draw "
          "(drawn jointly with the book's, so the book's own-noise spread is unchanged). Options on names not held (the USO puts) "
          "keep an independent draw, as before."]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(json.dumps(res, indent=1, default=float))


if __name__ == "__main__":
    main()
